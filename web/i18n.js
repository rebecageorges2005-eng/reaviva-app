/* ---------- helpers ---------- */
function getLang(){
  try{
    const l = localStorage.getItem("reaviva_lang");
    if(l && I18N[l]) return l;
  }catch(e){}
  // Detectar idioma del navegador (solo los 4 soportados).
  try{
    const b = (navigator.language || "es").slice(0,2).toLowerCase();
    if(I18N[b]) return b;
  }catch(e){}
  return "es";
}
function setLang(code){
  if(!I18N[code]) code = "es";
  try{ localStorage.setItem("reaviva_lang", code); }catch(e){}
  applyI18n();
  // Re-renderizar el contenido dinámico visible (chat, perfil, etc.).
  try{
    if(typeof switchTab === "function"){
      const active = document.querySelector(".tab.active");
      if(active && active.dataset.tab) switchTab(active.dataset.tab);
    }
  }catch(e){}
}
/* t('clave') → texto traducido; {d} y {n} se reemplazan con params. */
function t(key, params){
  const lang = getLang();
  let s = (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
  if(params){
    Object.keys(params).forEach(k => { s = s.split("{"+k+"}").join(params[k]); });
  }
  return s;
}
/* Aplica traducciones a todo [data-i18n] y [data-i18n-ph] del DOM. */
function applyI18n(){
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.innerHTML = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  // Marcar el idioma activo en el selector.
  document.querySelectorAll(".lang-opt").forEach(b => {
    b.classList.toggle("active", b.dataset.lang === getLang());
  });
  // Actualizar <html lang>.
  try{ document.documentElement.lang = getLang(); }catch(e){}
}
